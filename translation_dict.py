def normalize_russian(text):
    """规范化俄语词"""
    if not text:
        return ''
    text = text.lower().strip()
    text = text.replace('\u0301', '').replace('\u0300', '')
    text = text.strip('.,!?;:()[]{}""\'\'')
    return text

def translate_word(russian_word):
    """
    翻译单个俄语词（三层策略）
    第一层：A1常用词修正词典（词形 -> lemma）
    第二层：大БКРС词典（quest_dictionary_bkrs，含aspect_ref跟踪）
    第三层：兜底占位【原词】
    """
    if not russian_word:
        return ''

    normalized = normalize_russian(russian_word)

    # ===== 第一层：A1常用词修正词典 =====
    if normalized in A1_CORE_DICT:
        return A1_CORE_DICT[normalized]

    try:
        lemma = lemmatize_word(normalized)
        if lemma and lemma != normalized and lemma in A1_CORE_DICT:
            return A1_CORE_DICT[lemma]
    except Exception:
        pass

    # ===== 第二层：大БКРС词典（含aspect_ref自动跟踪） =====
    result = _lookup_bkrs(normalized)
    if result and result.strip():
        return result

    try:
        lemma = lemmatize_word(normalized)
        if lemma and lemma != normalized:
            result = _lookup_bkrs(lemma)
            if result and result.strip():
                return result
    except Exception:
        pass

    # ===== 第三层：兜底占位 =====
    return '【' + russian_word + '】'


def translate_phrase(russian_phrase):
    """
    翻译俄语短语
    优先级：A1短语词典 → 大БКРС短语级翻译 → 逐词翻译
    """
    if not russian_phrase:
        return ''

    normalized = normalize_russian(russian_phrase)

    # 1. 先查A1_CORE_DICT中的高频短语（如 "доброе утро" → "早上好"）
    if normalized in A1_CORE_DICT:
        return A1_CORE_DICT[normalized]

    # 2. 查大БКРС短语级翻译（如 "до свидания" → "再见"）
    result = _lookup_bkrs(normalized)
    if result and result.strip() and result != '【' + normalized + '】':
        return result

    # 3. 逐词翻译
    words = russian_phrase.split()
    translated_words = [translate_word(w) for w in words]
    return ''.join(translated_words)

def translate_chunk(russian_text):
    """
    翻译意群（自动判断是单词还是短语）
    """
    if not russian_text:
        return ''
    if ' ' in russian_text:
        return translate_phrase(russian_text)
    else:
        return translate_word(russian_text)

