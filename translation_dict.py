def _lookup_bkrs(word):
    if not word:
        return None
    cache_key = word.lower()
    if cache_key in _translation_cache:
        return _translation_cache[cache_key]

    # 优先使用内存词典
    bkrs = _load_bkrs_memory()
    if bkrs:
        lemma = word.lower()
        if lemma in bkrs:
            entry = bkrs[lemma]
            translation = entry.get('translation', '')
            aspect_ref = entry.get('aspect_ref', '')
            if aspect_ref and ('см.' in translation or len(translation.strip()) < 15):
                # 跟踪aspect_ref
                ref_lemma = aspect_ref.lower()
                if ref_lemma in bkrs:
                    result = clean_translation(bkrs[ref_lemma].get('translation', ''))
                else:
                    result = clean_translation(translation)
            else:
                result = clean_translation(translation)
            _translation_cache[cache_key] = result
            return result
        else:
            _translation_cache[cache_key] = None
            return None

    # 内存词典不可用时，回退到数据库查询
    for attempt in range(3):
        try:
            conn = _get_db_connection()
            cursor = conn.cursor()
            cursor.execute("""
                SELECT lemma, word_form, translation, aspect_ref
                FROM quest_dictionary_bkrs
                WHERE lemma = %s OR word_form = %s
                LIMIT 3
            """, (word.lower(), word))
            rows = cursor.fetchall()
            result = None
            if rows:
                main = rows[0]
                translation = main[2] or ''
                aspect_ref = main[3]
                if aspect_ref and ('см.' in translation or len(translation.strip()) < 15):
                    cursor.execute("""
                        SELECT translation FROM quest_dictionary_bkrs
                        WHERE lemma = %s
                        LIMIT 1
                    """, (aspect_ref,))
                    ref_row = cursor.fetchone()
                    if ref_row and ref_row[0]:
                        result = clean_translation(ref_row[0])
                    else:
                        result = clean_translation(translation)
                else:
                    result = clean_translation(translation)
            cursor.close()
            conn.close()
            _translation_cache[cache_key] = result
            return result
        except Exception as e:
            if attempt < 2:
                import time
                time.sleep(0.5)
                continue
            else:
                print(f"BKRS查询错误（3次重试失败）: {word} - {e}")
                return None
    return None

# 初始化词形还原器（natasha 缺失时为 None，仅原形直查）
_morph_vocab = MorphVocab() if MorphVocab else None

def lemmatize_word(word):
    """用Natasha将词还原为原形（lemma）"""
    if not word:
        return ''
    if MorphVocab is None or _morph_vocab is None:
        return word.lower()
    try:
        from natasha import Doc, Segmenter, NewsEmbedding, NewsMorphTagger
        segmenter = Segmenter()
        emb = NewsEmbedding()
        morph_tagger = NewsMorphTagger(emb)
        doc = Doc(word)
        doc.segment(segmenter)
        doc.tag_morph(morph_tagger)
        for token in doc.tokens:
            token.lemmatize(_morph_vocab)
            if token.lemma:
                return token.lemma
    except Exception:
        pass
    return word.lower()

