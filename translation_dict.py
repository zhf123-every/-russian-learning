def clean_translation(text):
    """清洗БКРС翻译结果：移除拼音、词性标注、俄语词头，保留中文"""
    if not text:
        return ''
    # 移除开头的俄语词头
    text = re.sub(r'^[а-яА-ЯёЁ]+\s*', '', text)
    # 移除拼音（拉丁字母含声调）
    text = re.sub(r'[a-zA-ZāáǎàēéěèīíǐìōóǒòūúǔùǖǘǚǜüĀÁǍÀĒÉĚÈĪÍǏÌŌÓǑÒŪÚǓÙǕǗǙǛ]+', '', text)
    # 保留中文词缀方括号，移除其他方括号
    text = re.sub(r'\[([\u4e00-\u9fff]+)\]', r'\1', text)
    text = re.sub(r'\[[^\]]*\]', '', text)
    # 移除罗马数字
    text = re.sub(r'\b[IVXLCDM]+\.\s*', '', text)
    # 移除俄语缩写
    text = re.sub(r'\b(?:нареч|сущ|гл|прил|мест|предл|союз|числ|межд|вводн|прич|дееприч|разг|устар|перен|тк|тж|сов|несов|см)\.?\s*', '', text)
    # 义项数字替换为分号
    text = re.sub(r'\s*\d+\.\s*', '; ', text)
    # 清理多余符号
    text = re.sub(r'\.{2,}', '', text)
    text = re.sub(r'—+', '', text)
    text = re.sub(r'\(\s*\)', '', text)
    text = re.sub(r'\s-\s', ' ', text)
    text = re.sub(r'-$', '', text)
    # 清理空格和标点
    text = re.sub(r'\s+', ' ', text)
    text = re.sub(r'\s*([,;，；])\s*', r'\1', text)
    text = re.sub(r'^[,;，；\s.]+', '', text)
    text = re.sub(r'[,;，；\s.]+$', '', text)
    text = re.sub(r'[;；]{2,}', ';', text)
    return text.strip()



